export function projectRole(project) {
  if (project.caseStudy?.role) return project.caseStudy.role
  const tags = project.tags || []
  if (tags.some(tag => /3d|visualis|visualiz/i.test(tag))) return 'Art Direction · Visualisation'
  if (tags.includes('Creative Direction')) return 'Art Direction · Creative Direction'
  return 'Art Direction'
}
